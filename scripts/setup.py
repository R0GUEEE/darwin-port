#!/usr/bin/env python3
"""Dependency-free installation and configuration front end for darwin-port."""
import argparse
import json
import os
import platform
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
KEYS = {'DARWIN_SDK', 'DARWIN_TARGET', 'DARWIN_MINOS', 'HOST_CLANG',
        'DS_SYSROOT', 'DS_LIB_PATH', 'DEVELOPER_DIR', 'APPLE_BIN'}
PACKAGES = {
    'apt-get': {'tools': ['python3', 'openssl'], 'ipa': ['python3', 'clang', 'lld'], 'core': ['python3', 'build-essential'],
                'full': ['python3', 'build-essential', 'clang', 'llvm', 'lld', 'openssl']},
    'apk': {'tools': ['python3', 'openssl'], 'ipa': ['python3', 'clang', 'lld'], 'core': ['python3', 'build-base'],
            'full': ['python3', 'build-base', 'clang', 'llvm', 'lld', 'openssl']},
    'dnf': {'tools': ['python3', 'openssl'], 'ipa': ['python3', 'clang', 'lld'], 'core': ['python3', 'gcc', 'make', 'glibc-devel'],
            'full': ['python3', 'gcc', 'make', 'glibc-devel', 'clang', 'llvm', 'lld', 'openssl']},
    'pacman': {'tools': ['python', 'openssl'], 'ipa': ['python', 'clang', 'lld'], 'core': ['python', 'base-devel'],
               'full': ['python', 'base-devel', 'clang', 'llvm', 'lld', 'openssl']},
}
SDK_DIRS = ['usr/include', 'usr/lib', 'System/Library/Frameworks']


def sdk_valid(path):
    return all((Path(path) / part).is_dir() for part in SDK_DIRS)


def read_config(path):
    """Read literal shell assignments without executing shell code."""
    result = {}
    if not path.exists():
        return result
    for number, line in enumerate(path.read_text().splitlines(), 1):
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        match = re.fullmatch(r'(?:export\s+)?([A-Z_]+)=(.*)', line.strip())
        if not match or match[1] not in KEYS:
            raise ValueError(f'{path}:{number}: expected a supported KEY=value assignment')
        words = shlex.split(match[2], comments=True)
        if len(words) > 1:
            raise ValueError(f'{path}:{number}: quote values containing spaces')
        value = words[0] if words else ''
        if any(c in value for c in '\n\r\0'):
            raise ValueError('configuration values cannot contain line breaks or NUL')
        result[match[1]] = value
    return result


def write_config(path, values):
    path.parent.mkdir(parents=True, exist_ok=True)
    body = '# Generated by darwin-port setup; literal shell assignments.\n'
    body += ''.join(f'{key}={shlex.quote(value)}\n' for key, value in sorted(values.items()))
    if path.exists() and path.read_text() == body:
        return
    if path.exists():
        shutil.copy2(path, path.with_name(path.name + '.bak'))
    fd, name = tempfile.mkstemp(prefix=path.name + '.', dir=path.parent)
    try:
        with os.fdopen(fd, 'w') as stream:
            stream.write(body)
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def resolve_profile(profile):
    native = platform.system() == 'Linux' and platform.machine().lower() in ('aarch64', 'arm64')
    if profile == 'auto':
        return 'full' if native else 'tools'
    if profile in ('core', 'full', 'sdk') and not native:
        raise ValueError('The loader requires ARM64 Linux. Use --profile tools for archive utilities '
                         'on this host; use an ARM64 Linux machine/VM for the loader.')
    return profile


def manager():
    return next((name for name in PACKAGES if shutil.which(name)), None)


def package_commands(pkg, profile, yes):
    packages = PACKAGES[pkg]['full' if profile == 'sdk' else profile]
    if pkg == 'apt-get':
        return [[pkg, 'update'], [pkg, 'install'] + (['-y'] if yes else []) + packages]
    if pkg == 'apk':
        return [[pkg, 'add'] + ([] if yes else ['--interactive']) + packages]
    if pkg == 'dnf':
        return [[pkg, 'install'] + (['-y'] if yes else []) + packages]
    return [[pkg, '-S', '--needed'] + (['--noconfirm'] if yes else []) + packages]


def settings(args):
    values = read_config(args.config)
    for key in KEYS:
        if key in os.environ:
            values[key] = os.environ[key]
    for item in args.set:
        key, sep, value = item.partition('=')
        if not sep or key not in KEYS:
            raise ValueError(f'unsupported setting: {item}; supported: {", ".join(sorted(KEYS))}')
        if any(c in value for c in '\n\r\0'):
            raise ValueError('configuration values cannot contain line breaks or NUL')
        values[key] = value
    if args.sdk:
        values['DARWIN_SDK'] = str(Path(args.sdk).expanduser().resolve())
    if args.no_sdk:
        values.pop('DARWIN_SDK', None)
    if not args.no_sdk and not values.get('DARWIN_SDK'):
        for candidate in ['/opt/xcode/MacOSX.sdk',
                          '/opt/Xcode.app/Contents/Developer/Platforms/MacOSX.platform/Developer/SDKs/MacOSX.sdk',
                          '/Applications/Xcode.app/Contents/Developer/Platforms/MacOSX.platform/Developer/SDKs/MacOSX.sdk']:
            if sdk_valid(candidate):
                values['DARWIN_SDK'] = candidate
                break
    if values.get('DARWIN_SDK'):
        values['DARWIN_SDK'] = str(Path(values['DARWIN_SDK']).expanduser().resolve())
        if not sdk_valid(values['DARWIN_SDK']):
            raise ValueError('SDK must contain usr/include, usr/lib, and System/Library/Frameworks')
    if args.profile == 'sdk' and not values.get('DARWIN_SDK'):
        raise ValueError('The sdk profile requires --sdk PATH or a valid saved/local SDK')
    for value in values.values():
        if any(c in value for c in '\n\r\0'):
            raise ValueError('configuration values cannot contain line breaks or NUL')
    values.setdefault('DARWIN_MINOS', '15.0')
    values.setdefault('DARWIN_TARGET', 'arm64-apple-macos' + values['DARWIN_MINOS'])
    values.setdefault('HOST_CLANG', 'clang')
    if not re.fullmatch(r'\d+(?:\.\d+){0,2}', values['DARWIN_MINOS']):
        raise ValueError('DARWIN_MINOS must be a version such as 15.0')
    if not re.fullmatch(r'(arm64|aarch64|x86_64)-apple-macos\d+(?:\.\d+){0,2}', values['DARWIN_TARGET']):
        raise ValueError('DARWIN_TARGET must be a macOS target triple, e.g. arm64-apple-macos15.0')
    return values


def diagnostics(profile, values):
    names = ['python3', 'openssl'] if profile == 'tools' else ['python3']
    if profile == 'ipa':
        names += ['clang', 'ld64.lld']
    elif profile != 'tools':
        names += ['make', 'cc']
    if profile in ('full', 'sdk'):
        names += [values['HOST_CLANG'], 'llvm-mc', 'ld64.lld', 'openssl']
    checks = [{'tool': name, 'path': shutil.which(name)} for name in dict.fromkeys(names)]
    return {'host': platform.system(), 'architecture': platform.machine(), 'profile': profile,
            'package_manager': manager(), 'checks': checks, 'sdk': values.get('DARWIN_SDK'),
            'ready': all(item['path'] for item in checks)}


def execute(command, env, log=None):
    print('+ ' + shlex.join(command), flush=True)
    if log is None:
        subprocess.run(command, cwd=ROOT, env=env, check=True)
        return
    with subprocess.Popen(command, cwd=ROOT, env=env, stdout=subprocess.PIPE,
                          stderr=subprocess.STDOUT, text=True, errors='replace') as process:
        for line in process.stdout:
            print(line, end='')
            log.write(line)
            log.flush()
        status = process.wait()
    if status:
        raise subprocess.CalledProcessError(status, command)


def parser():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('action', nargs='?', default='wizard',
                   choices=['wizard', 'plan', 'install', 'configure', 'doctor', 'env', 'run'])
    p.add_argument('--profile', choices=['auto', 'tools', 'ipa', 'core', 'full', 'sdk'], default='auto')
    p.add_argument('--config', type=lambda s: Path(s).expanduser().resolve(),
                   default=Path(os.environ.get('DARWIN_PORT_CONFIG', str(ROOT / 'darwin-port.env'))).expanduser().resolve())
    sdk = p.add_mutually_exclusive_group()
    sdk.add_argument('--sdk', help='existing MacOSX.sdk directory (never downloaded)')
    sdk.add_argument('--no-sdk', action='store_true', help='clear/ignore the SDK setting')
    p.add_argument('--set', action='append', default=[], metavar='KEY=VALUE')
    p.add_argument('--yes', action='store_true', help='approve package manager prompts')
    p.add_argument('--no-packages', action='store_true', help='use dependencies already on PATH')
    p.add_argument('--no-tests', action='store_true', help='build without loader compatibility tests')
    p.add_argument('--dry-run', '--check-only', action='store_true', help='read-only plan; never build or write')
    p.add_argument('--json', action='store_true', help='machine-readable plan or diagnostics')
    p.add_argument('--jobs', type=int, default=min(os.cpu_count() or 1, 8))
    p.add_argument('--log', type=Path, help='installation build/test log (default build/setup.log)')
    return p


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    command = []
    if '--' in argv:
        index = argv.index('--')
        command, argv = argv[index + 1:], argv[:index]
    args = parser().parse_args(argv)
    if command and args.action != 'run':
        raise ValueError('commands after -- are only supported with run')
    if args.jobs < 1:
        raise ValueError('--jobs must be positive')
    if args.action == 'wizard':
        if not sys.stdin.isatty():
            raise ValueError('Wizard requires a terminal. Use plan or install --yes for automation.')
        print('darwin-port setup — Apple SDKs are supplied separately.')
        print('Profiles: auto, tools (archive utilities), ipa (iOS cross-build), core (ARM64 loader), full, sdk')
        args.profile = input(f'Profile [{args.profile}]: ').strip() or args.profile
        if args.profile not in ('auto', 'tools', 'ipa', 'core', 'full', 'sdk'):
            raise ValueError('unknown profile')
        if not args.no_sdk and not args.sdk:
            args.sdk = input('Existing MacOSX.sdk path [optional]: ').strip() or None
        args.action = 'install'
        # Preview before any mutation, even when a wizard is invoked with --yes.
        args.yes = False
    profile = resolve_profile(args.profile)
    values = settings(args)
    env = dict(os.environ, **values)
    if args.no_sdk:
        env.pop('DARWIN_SDK', None)
    if args.action == 'env':
        for key, value in sorted(values.items()):
            print(f'export {key}={shlex.quote(value)}')
        print('export PATH=' + shlex.quote(str(ROOT / 'bin')) + ':' + shlex.quote(str(ROOT)) + ':"$PATH"')
        return 0
    if args.action == 'run':
        if not command:
            raise ValueError('Usage: setup.sh run -- COMMAND [ARG ...]')
        env['PATH'] = os.pathsep.join([str(ROOT / 'bin'), str(ROOT), env.get('PATH', '')])
        if args.dry_run:
            print(shlex.join(command))
        else:
            execute(command, env)
        return 0
    report = diagnostics(profile, values)
    pkg = report['package_manager']
    commands = [] if args.no_packages or not pkg else package_commands(pkg, profile, args.yes)
    build_enabled = profile in ('core', 'full', 'sdk')
    report.update(config=str(args.config), packages=commands,
                  build=build_enabled, tests=profile in ('full', 'sdk') and not args.no_tests)
    if args.json:
        print(json.dumps(report, indent=2))
    else:
        print(f"Host: {report['host']} {report['architecture']} | profile: {profile}")
        for check in report['checks']:
            print(f"{'OK' if check['path'] else 'MISSING'} {check['tool']}: {check['path'] or 'install required'}")
        print('SDK: ' + (report['sdk'] or 'not configured (optional)'))
        print('Config: ' + str(args.config))
        for cmd in commands:
            print('Package step: ' + shlex.join(cmd))
        print(f"Build loader: {report['build']} | compatibility tests: {report['tests']}")
    if args.action == 'plan' or args.dry_run:
        return 0
    if args.action == 'doctor':
        return 0 if report['ready'] else 1
    if args.action == 'configure':
        write_config(args.config, values)
        print('Saved configuration. Use ./setup.sh run -- COMMAND or eval "$(./setup.sh env)".')
        return 0
    if not args.no_packages:
        if not pkg:
            raise ValueError('No supported package manager. Install dependencies manually and use --no-packages.')
        if not args.yes:
            if not sys.stdin.isatty():
                raise ValueError('Use --yes for unattended package installation, or --no-packages.')
            if input('Install the listed packages and configure this checkout? [y/N] ').lower() not in ('y', 'yes'):
                print('Cancelled; nothing changed.')
                return 0
        prefix = []
        if os.geteuid() != 0:
            if not shutil.which('sudo'):
                raise ValueError('Package installation requires root or sudo; alternatively use --no-packages.')
            prefix = ['sudo']
        for cmd in package_commands(pkg, profile, True):
            execute(prefix + cmd, env)
    if not diagnostics(profile, values)['ready']:
        raise ValueError('Required tools are still missing. Run doctor and fix PATH before retrying.')
    write_config(args.config, values)
    if profile in ('core', 'full', 'sdk'):
        log_path = args.log or ROOT / 'build' / 'setup.log'
        log_path.parent.mkdir(parents=True, exist_ok=True)
        with log_path.open('a') as log:
            execute(['make', f'-j{args.jobs}', 'all'], env, log)
            if report['tests']:
                execute(['make', 'test'], env, log)
        print('Build/test log: ' + str(log_path))
    print('Setup complete. Use ./setup.sh run -- COMMAND or eval "$(./setup.sh env)".')
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (ValueError, OSError, subprocess.CalledProcessError) as exc:
        print(f'setup: {exc}', file=sys.stderr)
        sys.exit(1)
    except (KeyboardInterrupt, EOFError):
        print('\nSetup cancelled.', file=sys.stderr)
        sys.exit(130)
